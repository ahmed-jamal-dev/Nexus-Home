namespace NexusHome.Domain.Entities;

using NexusHome.Domain.Enums;

/// <summary>
/// Home membership invitation or claim credential.
/// Per DATABASE_MVP_SUMMARY.md and v1.3 baseline Section 6.2.7.
/// Role allows 'owner', 'member', 'guest'.
/// Business logic should restrict Owner invitations (I-05 unresolved).
/// For claim credentials: Role=Owner, InviteeEmail=null, Token=SHA256 hash.
/// </summary>
public class Invitation : Entity
{
    /// <summary>
    /// Home ID.
    /// </summary>
    public Guid HomeId { get; private set; }

    /// <summary>
    /// Invitee email address (null for claim credentials).
    /// </summary>
    public string? InviteeEmail { get; private set; }

    /// <summary>
    /// Proposed role (owner, member, guest).
    /// </summary>
    public Role Role { get; private set; }

    /// <summary>
    /// Unique invitation token (SHA-256 hash for claim credentials).
    /// </summary>
    public string Token { get; private set; } = string.Empty;

    /// <summary>
    /// Expiration timestamp.
    /// </summary>
    public DateTimeOffset ExpiresAt { get; private set; }

    /// <summary>
    /// Whether the invitation has been accepted.
    /// </summary>
    public bool IsAccepted { get; private set; } = false;

    /// <summary>
    /// User who sent the invitation (null for claim credentials generated by system).
    /// </summary>
    public Guid? InvitedByUserId { get; private set; }

    /// <summary>
    /// Navigation to home.
    /// </summary>
    public Home? Home { get; private set; }

    /// <summary>
    /// Navigation to inviter.
    /// </summary>
    public User? InvitedByUser { get; private set; }

    protected Invitation() { }

    public Invitation(Guid id, Guid homeId, string? inviteeEmail, Role role,
        string token, DateTimeOffset expiresAt, Guid? invitedByUserId = null)
        : base(id)
    {
        HomeId = homeId;
        InviteeEmail = inviteeEmail;
        Role = role;
        Token = token;
        ExpiresAt = expiresAt;
        InvitedByUserId = invitedByUserId;
    }

    /// <summary>
    /// Creates a claim credential for home ownership.
    /// Claim credentials have Role=Owner, InviteeEmail=null, and store SHA-256 hash of the credential.
    /// </summary>
    public static Invitation CreateClaimCredential(
        Guid homeId,
        string credentialHash,
        DateTimeOffset expiresAt,
        Guid? provisionerId = null)
    {
        return new Invitation(
            Guid.NewGuid(),
            homeId,
            inviteeEmail: null,
            Role.Owner,
            credentialHash,
            expiresAt,
            provisionerId);
    }

    /// <summary>
    /// Creates a member invitation.
    /// </summary>
    public static Invitation CreateMemberInvitation(
        Guid homeId,
        string inviteeEmail,
        Role role,
        string tokenHash,
        DateTimeOffset expiresAt,
        Guid? invitedByUserId = null)
    {
        return new Invitation(
            Guid.NewGuid(),
            homeId,
            inviteeEmail,
            role,
            tokenHash,
            expiresAt,
            invitedByUserId);
    }

    /// <summary>
    /// Marks the invitation as accepted.
    /// </summary>
    public void Accept()
    {
        IsAccepted = true;
        Touch();
    }

    /// <summary>
    /// Revokes the claim credential by clearing the token hash and setting expiry to now.
    /// </summary>
    public void Revoke()
    {
        Token = string.Empty;
        ExpiresAt = DateTimeOffset.UtcNow;
        Touch();
    }

    /// <summary>
    /// Checks if this is a claim credential (vs a member invitation).
    /// </summary>
    public bool IsClaimCredential => InviteeEmail == null && Role == Role.Owner;

    /// <summary>
    /// Checks if the invitation/credential is expired.
    /// </summary>
    public bool IsExpired => DateTimeOffset.UtcNow > ExpiresAt;

    /// <summary>
    /// Checks if the invitation/credential is valid (not accepted, not expired, has token).
    /// </summary>
    public bool IsValid => !IsAccepted && !IsExpired && !string.IsNullOrEmpty(Token);
}